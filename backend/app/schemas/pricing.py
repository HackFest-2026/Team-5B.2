"""Pricing decision (business view) and customer quote (customer-safe view)."""

from __future__ import annotations

from typing import Any, Optional

from pydantic import Field

from .common import StrictModel
from .optimizer import ModelInfo, SelectionStatus
from .persona import PersonaReaction, ShadowValidation
from .pricing_parts import (
    AppliedRule,
    Bounds,
    ConstraintEval,
    DecisionStatus,
    OverriddenRule,
    PriceRequest,
    SkippedRule,
    Violation,
)
from .strategy import Objective


class DecisionCandidate(StrictModel):
    price: float
    reasons: list[str]
    eligible: bool
    violations: list[Violation] = Field(default_factory=list)
    p_buy: Optional[float] = None
    expected_revenue: Optional[float] = None
    expected_profit: Optional[float] = None
    selection_status: SelectionStatus
    explanation: str = ""


class Explanation(StrictModel):
    business: list[str] = Field(default_factory=list)
    customer: list[str] = Field(default_factory=list)


class Provenance(StrictModel):
    optimizer: Optional[ModelInfo] = None
    personas: Optional[str] = None
    llm_generated_strategy: bool = False
    simulated: bool = True


class PricingDecision(StrictModel):
    decision_id: str
    domain_id: str
    product_id: str
    strategy_version_id: str
    version_number: Optional[int] = None
    status: DecisionStatus
    status_reason: Optional[str] = None
    final_price: Optional[float] = None
    currency: str
    unit_label: str = ""
    unit_prefix: str = ""
    unit_suffix: str = ""
    decimals: int = 2
    objective: Objective
    reference_price: float
    anchor_price: float
    bounds: Bounds
    applied_rules: list[AppliedRule] = Field(default_factory=list)
    overridden_rules: list[OverriddenRule] = Field(default_factory=list)
    skipped_rules: list[SkippedRule] = Field(default_factory=list)
    constraints_evaluated: list[ConstraintEval] = Field(default_factory=list)
    candidates: list[DecisionCandidate] = Field(default_factory=list)
    persona_summary: Optional[list[PersonaReaction]] = None
    shadow_validation: Optional[ShadowValidation] = None
    explanation: Explanation = Field(default_factory=Explanation)
    provenance: Provenance = Field(default_factory=Provenance)
    signals: dict[str, float] = Field(default_factory=dict)
    context_snapshot: dict[str, Any] = Field(default_factory=dict)
    request: PriceRequest
    warnings: list[str] = Field(default_factory=list)
    created_at: Optional[str] = None


class Alternative(StrictModel):
    price: float
    label: str


class CustomerQuote(StrictModel):
    """Customer-safe view: no cost, margin, purchase probability, rule ids or validation internals."""

    decision_id: str
    status: DecisionStatus
    final_price: Optional[float] = None
    currency: str
    unit_label: str = ""
    unit_prefix: str = ""
    unit_suffix: str = ""
    decimals: int = 2
    factors: list[str] = Field(default_factory=list)
    alternatives: Optional[list[Alternative]] = None
    notice: str = "Prices are generated by a demo engine; purchase predictions come from models built on synthetic data."

