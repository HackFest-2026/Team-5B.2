"""
features.py — Domain-Agnostic Feature Schema & Engineering

This module defines the EXACT feature set used for model training.
Every feature here is a normalized ratio or a universal behavioral signal.
There is ZERO domain-specific information (no product categories, no room types, etc.)

FEATURE GROUPS:
===============
  PRICE FEATURES (5):
    price_ratio, log_price_ratio, price_vs_competitor,
    margin_ratio, price_rank_normalized

  CUSTOMER FEATURES (2):
    customer_sensitivity, customer_loyalty_score

  MARKET FEATURES (6):
    urgency_score, scarcity_score, demand_pressure,
    competitor_density, is_promotion_active, time_decay_factor

  VALUE FEATURES (1):
    perceived_value_gap

  Total: 14 features (all numeric — no categorical encoding needed)

TARGET:
=======
  purchased (0 or 1)

LEAKAGE EXCLUSIONS:
===================
  true_purchase_probability — simulator ground truth, never in X
  candidate_price, base_price, unit_cost — raw $ amounts (domain-identifying)
  product_id, customer_id, quote_id — identifiers only
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


# ---------------------------------------------------------------------------
# Feature column definitions
# ---------------------------------------------------------------------------

PRICE_FEATURES = [
    "price_ratio",              # candidate_price / base_price (centered at 1.0)
    "log_price_ratio",          # log(price_ratio) — symmetrizes discounts/premiums
    "price_vs_competitor",      # candidate_price / competitor_price (>1 = overpriced)
    "margin_ratio",             # (candidate - cost) / base_price (business health)
    "price_rank_normalized",    # rank among candidates (0=cheapest, 1=most expensive)
]

CUSTOMER_FEATURES = [
    "customer_sensitivity",     # 0-1 price sensitivity score
    "customer_loyalty_score",   # 0-1 loyalty / stickiness
]

MARKET_FEATURES = [
    "urgency_score",            # 0-1 how urgently the customer needs this
    "scarcity_score",           # 0-1 how scarce the supply is
    "demand_pressure",          # 0-2 aggregate demand level (1.0=normal)
    "competitor_density",       # 0-1 how many competitors exist
    "is_promotion_active",      # 0 or 1
    "time_decay_factor",        # 0-1 time pressure (offer expiry, booking window)
]

VALUE_FEATURES = [
    "perceived_value_gap",      # (perceived_value - price) / base_price
]

# All training features (14 total)
ALL_FEATURES = PRICE_FEATURES + CUSTOMER_FEATURES + MARKET_FEATURES + VALUE_FEATURES
TARGET_COL = "purchased"

# Fields that MUST NEVER enter the feature matrix X
LEAKAGE_FIELDS = {
    "true_purchase_probability",   # ground truth from simulator
    "candidate_price",             # raw dollar amount (domain-identifying)
    "base_price",                  # raw dollar amount
    "unit_cost",                   # raw dollar amount
    "competitor_price",            # raw dollar amount
    "product_id",                  # identifier
    "customer_id",                 # identifier
    "quote_id",                    # identifier
    "candidate_idx",               # ordering info
}


def load_training_data(data_dir: Path) -> pd.DataFrame:
    """
    Load the training data CSV generated by generate_dataset.py.
    Validates that required columns exist.
    """
    csv_path = data_dir / "training_data.csv"
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Training data not found at {csv_path}. "
            "Run generate_dataset.py first."
        )

    df = pd.read_csv(csv_path)
    print(f"[features] Loaded {len(df):,} rows from {csv_path}")

    # Validate columns
    missing_features = [f for f in ALL_FEATURES if f not in df.columns]
    if missing_features:
        raise ValueError(f"Missing feature columns: {missing_features}")
    if TARGET_COL not in df.columns:
        raise ValueError(f"Missing target column: {TARGET_COL}")

    # Check for leakage
    for col in LEAKAGE_FIELDS:
        if col in ALL_FEATURES:
            raise ValueError(f"LEAKAGE DETECTED: {col} is in ALL_FEATURES!")

    return df


def get_X_y(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.Series]:
    """
    Extract feature matrix X and target vector y from the DataFrame.
    Only includes columns in ALL_FEATURES — nothing else.
    """
    available = [f for f in ALL_FEATURES if f in df.columns]
    X = df[available].copy()
    y = df[TARGET_COL].astype(int)

    # Sanity checks
    for col in LEAKAGE_FIELDS:
        assert col not in X.columns, f"LEAKAGE: {col} found in X!"

    return X, y


def random_split(
    df: pd.DataFrame,
    train_frac: float = 0.70,
    val_frac: float = 0.15,
    seed: int = 42,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Random stratified split into train/val/test.
    (Since our dataset has no temporal ordering, random split is appropriate.)
    """
    from sklearn.model_selection import train_test_split

    # First split: train+val vs test
    train_val, test = train_test_split(
        df, test_size=1.0 - train_frac - val_frac,
        stratify=df[TARGET_COL], random_state=seed,
    )

    # Second split: train vs val
    val_ratio = val_frac / (train_frac + val_frac)
    train, val = train_test_split(
        train_val, test_size=val_ratio,
        stratify=train_val[TARGET_COL], random_state=seed,
    )

    print(f"\n[features] Split summary:")
    for name, split in [("Train", train), ("Val", val), ("Test", test)]:
        n = len(split)
        pos = split[TARGET_COL].sum()
        print(f"  {name:5s}: {n:>7,} rows | {pos/n:.1%} purchased")

    return train.reset_index(drop=True), val.reset_index(drop=True), test.reset_index(drop=True)


def build_candidate_features(
    candidate_price: float,
    base_price: float,
    unit_cost: float,
    competitor_price: float,
    candidate_rank_normalized: float,
    customer_sensitivity: float,
    customer_loyalty_score: float,
    urgency_score: float = 0.3,
    scarcity_score: float = 0.3,
    demand_pressure: float = 1.0,
    competitor_density: float = 0.5,
    is_promotion_active: int = 0,
    time_decay_factor: float = 0.5,
    perceived_value_gap: float | None = None,
) -> dict:
    """
    Build a single feature row for inference.
    This is used by predict_best_price.py to score candidate prices.

    All dollar amounts are converted to domain-agnostic ratios.
    """
    bp = max(base_price, 0.01)
    cp_comp = max(competitor_price, 0.01)

    price_ratio = float(np.clip(candidate_price / bp, 0.1, 10.0))
    log_price_ratio = float(np.log(price_ratio))
    price_vs_competitor = float(np.clip(candidate_price / cp_comp, 0.1, 10.0))
    margin_ratio = float((candidate_price - unit_cost) / bp)

    # If perceived value gap not provided, estimate from loyalty + demand
    if perceived_value_gap is None:
        perceived_value = bp * (1.0 + 0.15 * customer_loyalty_score + 0.10 * (demand_pressure - 1.0))
        perceived_value_gap = float((perceived_value - candidate_price) / bp)

    return {
        "price_ratio": round(price_ratio, 4),
        "log_price_ratio": round(log_price_ratio, 4),
        "price_vs_competitor": round(price_vs_competitor, 4),
        "margin_ratio": round(margin_ratio, 4),
        "price_rank_normalized": round(candidate_rank_normalized, 4),
        "customer_sensitivity": round(customer_sensitivity, 4),
        "customer_loyalty_score": round(customer_loyalty_score, 4),
        "urgency_score": round(urgency_score, 4),
        "scarcity_score": round(scarcity_score, 4),
        "demand_pressure": round(demand_pressure, 4),
        "competitor_density": round(competitor_density, 4),
        "is_promotion_active": int(is_promotion_active),
        "time_decay_factor": round(time_decay_factor, 4),
        "perceived_value_gap": round(perceived_value_gap, 4),
    }
